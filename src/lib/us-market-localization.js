export function localizeUsCompanyMeta(instrument, isArabic) {
  if (!isArabic) return {
    industry: instrument.industry_en || "",
    country: instrument.issuer_country || "",
    listing: instrument.ipo_year ? `IPO ${instrument.ipo_year}` : "",
  };
  const industryKey = String(instrument.industry_en || "").trim();
  return {
    industry: INDUSTRY_AR[industryKey] || industryKey,
    country: COUNTRY_AR[instrument.issuer_country] || instrument.issuer_country || "",
    listing: instrument.ipo_year ? `إدراج ${instrument.ipo_year}` : "",
  };
}
